import { expect, test } from "@playwright/test";
import { z } from "zod";

test.skip(process.env.AVAILABILITY_LIVE_PROOF !== "1", "Requires the disposable localhost:3200 proof API");
test.use({ video: "on" });
const api = "http://localhost:3200/api/v1/advisors/me/availability";
const profileSchema = z.object({ id: z.uuid(), name: z.string(), weeklyWindows: z.array(z.object({ dayOfWeek: z.number(), startTime: z.string(), endTime: z.string() })), specificWindows: z.array(z.object({ availableDate: z.string() })), blockedPeriods: z.array(z.object({ blockedDate: z.string() })) });
const globalSchema = z.object({ bookingHorizonDays: z.number(), bufferMinutes: z.number(), minimumBookingNoticeMinutes: z.number(), dailyConsultationLimitMinutes: z.number().nullable() });

for (const width of [1440, 390]) {
  test(`availability changes survive refresh at ${width}px`, async ({ page, context }) => {
    test.setTimeout(120_000);
    await page.setViewportSize({ width, height: 1000 });
    const errors: string[] = [];
    page.on("pageerror", (error) => errors.push(error.message));
    expect((await context.request.post("http://localhost:3200/api/auth/sign-in/email", {
      data: { email: "kanya.p@advisory.demo", password: "AdvisoryDemo!2026" },
      headers: { origin: "http://localhost:3001" },
    })).status()).toBe(200);
    const globalResponse = await context.request.get(`${api}/global`);
    expect(globalResponse.status(), await globalResponse.text()).toBe(200);
    const originalGlobal = globalSchema.parse((await globalResponse.json()).data);
    let profileId = "";
    let linkedServiceId = "";
    try {
      await page.goto("/availability/profiles/new/from-list");
      const name = `Availability proof ${width}`;
      await page.locator('input[name="name"]').fill(name);
      await page.getByRole("button", { name: "เสาร์–อาทิตย์", exact: true }).click();
      await expect(page.getByRole("switch", { name: "จันทร์", exact: true })).not.toBeChecked();
      await expect(page.getByRole("switch", { name: "เสาร์", exact: true })).toBeChecked();
      await page.getByRole("button", { name: "ทุกวัน 09:00–17:00", exact: true }).click();
      await expect(page.getByRole("switch", { name: "จันทร์", exact: true })).toBeChecked();
      await page.getByRole("button", { name: "จ–ศ 09:00–17:00", exact: true }).click();
      const monday = page.getByRole("switch", { name: "จันทร์", exact: true });
      await monday.click();
      await expect(page.locator('input[name="weeklyStart-mon-0"]')).toHaveCount(0);
      await monday.click();
      await expect(page.locator('input[name="weeklyStart-mon-0"]')).toHaveValue("09:00");
      const created = page.waitForResponse((r) => r.url() === `${api}/profiles` && r.request().method() === "POST");
      await page.locator('button[type="submit"]').filter({ visible: true }).click();
      const response = await created;
      expect(response.status()).toBe(201);
      profileId = profileSchema.parse((await response.json()).data).id;
      await expect(page).toHaveURL(new RegExp(`id=${profileId}`));
      await page.reload();
      await expect(page.locator('input[name="name"]')).toHaveValue(name);
      await page.locator('input[name="name"]').fill(`${name} edited`);
      await page.locator('input[name="weeklyStart-mon-0"]').fill("09:00");
      await page.locator('input[name="weeklyEnd-mon-0"]').fill("12:00");
      await page.locator('input[name="weeklyStart-mon-1"]').fill("11:00");
      await page.locator('input[name="weeklyEnd-mon-1"]').fill("13:00");
      await page.locator('button[type="submit"]').filter({ visible: true }).click();
      await expect(page.getByRole("alert").filter({ hasText: "ช่วงเวลาทับซ้อนกัน" })).toBeVisible();
      await page.locator('input[name="weeklyStart-mon-1"]').fill("");
      await page.locator('input[name="weeklyEnd-mon-1"]').fill("");
      await context.setOffline(true);
      await page.locator('button[type="submit"]').filter({ visible: true }).click();
      await expect(page.getByRole("alert").filter({ hasText: "API" })).toBeVisible();
      await expect(page.locator('input[name="name"]')).toHaveValue(`${name} edited`);
      await context.setOffline(false);
      const saveWeekly = page.waitForResponse((r) => r.url() === `${api}/profiles/${profileId}` && r.request().method() === "PATCH");
      await page.locator('button[type="submit"]').filter({ visible: true }).click();
      expect((await saveWeekly).status()).toBe(200);
      await page.goto(`/availability/profiles/edit/specific?id=${profileId}`);
      await expect(page.locator('input[name^="specificStart-"]')).toHaveCount(0);
      await expect(page.getByText("ยังไม่มีวันที่เฉพาะ", { exact: true })).toBeVisible();
      await page.locator('input[name="newSpecificDate"]').fill("2099-06-12");
      await page.locator('input[name="newSpecificStart"]').fill("10:00");
      await page.locator('input[name="newSpecificEnd"]').fill("11:00");
      const saveSpecific = page.waitForResponse((r) => r.url() === `${api}/profiles/${profileId}` && r.request().method() === "PATCH");
      await page.locator('button[type="submit"]').filter({ visible: true }).click();
      expect((await saveSpecific).status()).toBe(200);
      await page.goto(`/availability/profiles/new/specific?id=${profileId}`);
      await page.reload();
      await expect(page.locator('input[name="specificStart-2099-06-12-0"]')).toHaveValue("10:00");
      const resaveSpecific = page.waitForResponse((r) => r.url() === `${api}/profiles/${profileId}` && r.request().method() === "PATCH");
      await page.locator('button[type="submit"]').filter({ visible: true }).click();
      expect((await resaveSpecific).status()).toBe(200);
      await page.goto(`/availability/profiles/edit/blocked?id=${profileId}`);
      await expect(page.getByText("ยังไม่มีวันที่ปิด", { exact: true })).toBeVisible();
      await page.locator('input[name="newBlockedDate"]').fill("2099-06-13");
      const saveBlocked = page.waitForResponse((r) => r.url() === `${api}/profiles/${profileId}` && r.request().method() === "PATCH");
      await page.locator('button[type="submit"]').filter({ visible: true }).click();
      expect((await saveBlocked).status()).toBe(200);
      await page.reload();
      await expect(page.getByText("2099-06-13", { exact: true })).toBeVisible();
      const profiles = z.array(profileSchema).parse((await (await context.request.get(`${api}/profiles`)).json()).data);
      const persisted = profiles.find((p) => p.id === profileId);
      expect(persisted?.name).toBe(`${name} edited`);
      expect(persisted?.weeklyWindows.find((w) => w.dayOfWeek === 1)).toMatchObject({ startTime: "09:00:00", endTime: "12:00:00" });
      expect(persisted?.specificWindows).toContainEqual(expect.objectContaining({ availableDate: "2099-06-12" }));
      expect(persisted?.blockedPeriods).toContainEqual(expect.objectContaining({ blockedDate: "2099-06-13" }));
      await page.screenshot({ path: `../.audit/availability-proof-2026-10-27/profile-${width}.png`, fullPage: true });
      await page.getByRole("checkbox", { name: "ลบ", exact: true }).check();
      const removeBlocked = page.waitForResponse((r) => r.url() === `${api}/profiles/${profileId}` && r.request().method() === "PATCH");
      await page.locator('button[type="submit"]').filter({ visible: true }).click();
      expect((await removeBlocked).status()).toBe(200);
      await page.reload();
      await expect(page.getByText("ยังไม่มีวันที่ปิด", { exact: true })).toBeVisible();
      expect(z.array(profileSchema).parse((await (await context.request.get(`${api}/profiles`)).json()).data).find((profile) => profile.id === profileId)?.blockedPeriods).toEqual([]);
      expect((await context.request.put(`${api}/global`, { data: { dailyConsultationLimitMinutes: null } })).status()).toBe(200);
      await page.goto("/availability");
      await expect(page.locator('input[name="horizon"][value="14"]')).toBeAttached();
      await page.locator('input[name="horizon"][value="custom"]').check({ force: true });
      await page.locator('input[name="customHorizon"]').fill("0");
      await page.locator('input[name="buffer"][value="10"]').check({ force: true });
      const limit = page.getByRole("switch", { name: "จำกัดชั่วโมงต่อวัน", exact: true });
      if (!(await limit.isChecked())) await limit.click();
      await page.locator("label").filter({ has: page.locator('input[name="dailyLimit"][value="6"]') }).click();
      await expect(page.locator('input[name="customDailyLimit"]')).toHaveCount(0);
      await limit.click();
      await limit.click();
      await expect(page.locator('input[name="dailyLimit"][value="custom"]')).toBeChecked();
      await expect(page.locator('input[name="customDailyLimit"]')).toBeVisible();
      await page.locator('input[name="dailyLimit"][value="custom"]').check({ force: true });
      await page.locator('input[name="customDailyLimit"]').fill("1.5");
      await page.locator('button[type="submit"]').filter({ visible: true }).click();
      await expect(page.getByRole("alert").filter({ hasText: "กรุณาตรวจสอบค่า" })).toBeVisible();
      await page.locator('input[name="customHorizon"]').fill("17");
      const saveGlobal = page.waitForResponse((r) => r.url() === `${api}/global` && r.request().method() === "PUT");
      await page.locator('button[type="submit"]').filter({ visible: true }).click();
      expect((await saveGlobal).status()).toBe(200);
      await page.reload();
      await expect(page.locator('input[name="horizon"][value="custom"]')).toBeChecked();
      await expect(page.locator('input[name="customHorizon"]')).toHaveValue("17");
      await expect(page.locator('input[name="customDailyLimit"]')).toHaveValue("1.5");
      await expect(page.locator('input[name="buffer"][value="10"]')).toBeChecked();
      expect(globalSchema.parse((await (await context.request.get(`${api}/global`)).json()).data)).toMatchObject({ bookingHorizonDays: 17, bufferMinutes: 10, dailyConsultationLimitMinutes: 90 });
      await page.screenshot({ path: `../.audit/availability-proof-2026-10-27/global-${width}.png`, fullPage: true });
      const servicesApi = "http://localhost:3200/api/v1/advisors/me/services";
      const categoryId = z.object({ data: z.object({ items: z.array(z.object({ categoryId: z.uuid() })).min(1) }) }).parse(await (await context.request.get(servicesApi)).json()).data.items[0].categoryId;
      const linkedService = await context.request.post(servicesApi, { data: {
        name: `Availability dependency proof ${width}`, categoryId, availabilityProfileId: profileId,
        priceSatang: 10000, durationMinutes: 30, isPublished: false,
      } });
      expect(linkedService.status()).toBe(201);
      linkedServiceId = z.object({ data: z.object({ id: z.uuid() }) }).parse(await linkedService.json()).data.id;
      await page.goto("/availability/profiles");
      const linkedCard = page.getByRole("article").filter({ has: page.getByRole("heading", { name: `${name} edited`, exact: true }) });
      await expect(linkedCard.getByRole("link", { name: "ลบ", exact: true })).toHaveCount(0);
      await page.goto(`/availability/profiles/delete?id=${profileId}`);
      const deniedDelete = page.waitForResponse((r) => r.url() === `${api}/profiles/${profileId}` && r.request().method() === "DELETE");
      await page.getByRole("alertdialog").getByRole("button", { name: "ลบชุดเวลา", exact: true }).click();
      expect((await deniedDelete).status()).toBe(409);
      await expect(page.getByRole("alertdialog").getByRole("alert")).toHaveText("Availability profile is assigned to a service");
      await page.screenshot({ path: `../.audit/availability-proof-2026-10-27/linked-profile-${width}.png`, fullPage: true });
      expect((await context.request.delete(`${servicesApi}/${linkedServiceId}`)).status()).toBe(200);
      linkedServiceId = "";
      const deleted = page.waitForResponse((r) => r.url() === `${api}/profiles/${profileId}` && r.request().method() === "DELETE");
      await page.getByRole("alertdialog").getByRole("button", { name: "ลบชุดเวลา", exact: true }).click();
      expect((await deleted).status()).toBe(200);
      await page.reload();
      await expect(page.getByRole("heading", { name: `${name} edited`, exact: true })).toHaveCount(0);
      expect(z.array(profileSchema).parse((await (await context.request.get(`${api}/profiles`)).json()).data).some((p) => p.id === profileId)).toBe(false);
      expect(errors).toEqual([]);
    } finally {
      await context.setOffline(false);
      if (linkedServiceId) await context.request.delete(`http://localhost:3200/api/v1/advisors/me/services/${linkedServiceId}`);
      if (profileId) await context.request.delete(`${api}/profiles/${profileId}`);
      expect((await context.request.put(`${api}/global`, { data: originalGlobal })).status()).toBe(200);
    }
  });
}
